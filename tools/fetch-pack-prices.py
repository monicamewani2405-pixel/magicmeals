"""Copy the old store's Pack of 3 / 5 / 7 prices (magicmeals.shop) into pack-prices.js.

    python tools/fetch-pack-prices.py

The old store sells 40 of its products as variations Single / Pack of 3 / Pack of 5 / Pack of 7 (the other products have one price only).
A product gets its 3/5/7 prices here ONLY when (a) the old store has those packs for it and (b) its single price there is the same as
our single price in main.js. Combos keep our own Pack of 3 / Pack of 6 prices (main.js calcPrice), and are listed in the report.
Every other SINGLE dish (not a combo) gets Pack of 3 / 5 / 7 by one rule: n x the single price, no discount. Combos keep Pack of 3 / Pack of 6.
Needs the id -> live slug MAP of tools/fetch-live-descriptions.py. Writes pack-prices.js: window.PACK_PRICES = { id: { '3': n, '5': n, '7': n } }.
"""
import concurrent.futures as cf
import html
import importlib.util
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
API = 'https://magicmeals.shop/wp-json/wc/store/v1/products'


def fetch(url):
    for _ in range(3):
        try:
            return json.load(urllib.request.urlopen(url, timeout=30))
        except Exception:
            pass
    raise SystemExit('could not read ' + url)


def site_prices():
    out, cur = {}, None
    for l in (ROOT / 'main.js').read_text(encoding='utf-8').split('\n'):
        m = re.match(r"\s+id: '([^']+)',\s*$", l)
        if m:
            cur = {'id': m.group(1)}
            continue
        if cur is None:
            continue
        m = re.match(r"\s+category: '(.*)',", l)
        if m:
            cur['has_cat'] = True
            cur['category'] = m.group(1)
        m = re.match(r"\s+price: (\d+),", l)
        if m and 'price' not in cur and cur.get('has_cat'):
            cur['price'] = int(m.group(1))
            out[cur['id']] = (cur['price'], cur['category'])
    return out


def main():
    spec = importlib.util.spec_from_file_location('fl', ROOT / 'tools' / 'fetch-live-descriptions.py')
    fl = importlib.util.module_from_spec(spec)
    sys.argv = ['x']
    spec.loader.exec_module(fl)
    MAP, EXTRA = fl.MAP, getattr(fl, 'EXTRA', {})

    old = []
    for page in (1, 2):
        old += fetch(f'{API}?per_page=100&page={page}')
    jobs = [(p['slug'], v['id'], v['attributes'][0]['value']) for p in old for v in p.get('variations', []) if v['attributes']]
    prices = {}
    with cf.ThreadPoolExecutor(8) as ex:
        futs = {ex.submit(fetch, f'{API}/{i}'): (s, a) for s, i, a in jobs}
        for f in cf.as_completed(futs):
            s, a = futs[f]
            prices.setdefault(s, {})[a] = int(f.result()['prices']['price']) / 100
    live = {p['slug']: (html.unescape(p['name']), p['type'], int(p['prices']['price']) / 100) for p in old}

    mine = site_prices()
    use, differ, nopack, notold, rule = {}, [], [], [], {}
    for pid, (price, category) in mine.items():
        slug = MAP.get(pid)
        if pid in EXTRA or slug is None or slug not in live:
            notold.append(pid)
            if category != 'Combos':
                rule[pid] = {n: price * int(n) for n in ('3', '5', '7')}
            continue
        name, typ, single = live[slug]
        pk = prices.get(slug, {})
        if typ != 'variable' or not all(k in pk for k in ('pack-of-3', 'pack-of-5', 'pack-of-7')):
            nopack.append(pid)
            if category != 'Combos':
                rule[pid] = {n: price * int(n) for n in ('3', '5', '7')}
            continue
        if pk.get('single', single) != price:
            differ.append((pid, price, pk.get('single', single), {k[-1]: pk[k] for k in ('pack-of-3', 'pack-of-5', 'pack-of-7')}))
            continue
        use[pid] = {n: int(round(pk[f'pack-of-{n}'])) for n in ('3', '5', '7')}

    use.update(rule)
    body = json.dumps(use, indent=1)
    (ROOT / 'pack-prices.js').write_text(
        '/* pack-prices.js: GENERATED by tools/fetch-pack-prices.py. Do not edit by hand.\n'
        '   Pack of 3 / 5 / 7 prices copied from the old store (magicmeals.shop), only for products that have these packs there AND the\n'
        '   same single price as here, plus every other single dish at n x its single price (no discount). Combos are not listed: they\n'
        '   keep Pack of 3 / Pack of 6 at the sites own prices (calcPrice in main.js). */\n'
        'window.PACK_PRICES = ' + body + ';\n', encoding='utf-8')
    print(f'pack-prices.js: {len(use)} products get Pack of 3 / 5 / 7 ({len(use) - len(rule)} copied from the old store, {len(rule)} by the rule n x single)')
    print('   rule:', ', '.join(rule))
    print(f'single price differs from the old store (left unchanged): {len(differ)}')
    for d in differ:
        print('   ', d)
    print(f'old store has no packs for them (left unchanged): {len(nopack)}')
    print(f'not on the old store (left unchanged): {len(notold)}', notold)


if __name__ == '__main__':
    main()
