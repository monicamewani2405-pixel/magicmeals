"""Derive a page tint and a text/accent ink for every product from its pouch, and write them as CSS tokens.

    python tools/pdp-tints.py

Reads  pouch-art/<slug>-front-processed.png  (every product that has one)
Writes pdp/pdp-tints.css  with  --pdp-tint-<slug>  and  --pdp-ink-<slug>  on :root.

tint = the pouch's dominant colour, washed out to a pale background (lightness ~94 %).
ink  = the same hue, darkened until white text on it has contrast >= 7:1 and it reads on the tint at >= 5:1
       (used for headings, chips and the active Front/Back button).
Dishes that already have hero tokens in style.css (--tint-<slug>, --ink-<slug>) just alias them, so the hero and the page match.
"""
import colorsys, os
from pathlib import Path

import numpy as np
from PIL import Image

REPO = Path(__file__).resolve().parent.parent
ROOT = Path(os.environ.get('PDP_ROOT') or REPO)
POUCH_DIR = REPO / 'pouch-art'
EXISTING = ['veg-biryani', 'rajma-masala', 'paneer-butter-masala', 'dal-makhani', 'pav-bhaji']   # have --tint-/--ink- tokens in style.css


def lum(rgb):
    def f(c):
        c /= 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = rgb
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)


def contrast(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def hexs(rgb):
    return '#%02X%02X%02X' % tuple(int(round(c)) for c in rgb)


def dominant_hue(path):
    """Most common pouch colour that is neither near-white, near-black nor grey (the printed pastel background)."""
    im = Image.open(path).convert('RGBA')
    a = np.asarray(im).astype(int)
    px = a[a[..., 3] > 250][:, :3]
    q = (px // 16) * 16 + 8
    mx, mn = q.max(1), q.min(1)
    sat = (mx - mn) / np.maximum(mx, 1)
    keep = (sat > 0.12) & (mx > 70) & (mn < 235)
    q = q[keep]
    if len(q) < 500:
        return 0.08, 0.3
    vals, counts = np.unique(q, axis=0, return_counts=True)
    r, g, b = vals[counts.argmax()] / 255
    h, s, _ = colorsys.rgb_to_hls(r, g, b)[0], colorsys.rgb_to_hsv(r, g, b)[1], 0
    return h, s


def make(h, s):
    st = min(0.55, max(0.30, s * 0.9))
    tint = tuple(c * 255 for c in colorsys.hls_to_rgb(h, 0.945, st))
    # ink: same hue, strong, darkened until it passes both contrast checks
    si = min(0.75, max(0.45, s))
    for l in np.arange(0.40, 0.12, -0.01):
        ink = tuple(c * 255 for c in colorsys.hls_to_rgb(h, l, si))
        if contrast(ink, (255, 255, 255)) >= 7 and contrast(ink, tint) >= 5:
            break
    return tint, ink


def main():
    slugs = sorted(p.name[:-len('-front-processed.png')] for p in POUCH_DIR.glob('*-front-processed.png'))
    lines = ['/* Generated by tools/pdp-tints.py: per-product page tint and ink, from the pouch colour. Do not edit by hand. */', ':root {']
    worst = 99
    for slug in slugs:
        if slug in EXISTING:
            lines.append(f'  --pdp-tint-{slug}: var(--tint-{slug});')
            lines.append(f'  --pdp-ink-{slug}: var(--ink-{slug});')
            continue
        h, s = dominant_hue(POUCH_DIR / f'{slug}-front-processed.png')
        tint, ink = make(h, s)
        worst = min(worst, contrast(ink, (255, 255, 255)), contrast(ink, tint))
        lines.append(f'  --pdp-tint-{slug}: {hexs(tint)};')
        lines.append(f'  --pdp-ink-{slug}: {hexs(ink)};')
        print(f'{slug:28s} tint {hexs(tint)}  ink {hexs(ink)}  ink/white {contrast(ink, (255, 255, 255)):.1f}  ink/tint {contrast(ink, tint):.1f}')
    lines.append('}')
    (ROOT / 'pdp' / 'pdp-tints.css').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{len(slugs)} products; lowest contrast among generated inks: {worst:.1f}:1')


if __name__ == '__main__':
    main()
